#!/usr/bin/env python3
"""Prints an appbench kv-session for the imdaxfs 'nm' grid: one kv-load, then 2 MiB-record readers over
U128 / U512 hot sets and Zipfian at each thread count, S (IM on) against S0 (IM off);
block 1 runs block 0's order reversed with the next seed."""

import argparse

REC = 2 << 20


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--node", type=int, required=True)
    ap.add_argument("--gib", type=float, default=1024)
    ap.add_argument("--threads", default="16,64,120")
    # Once the device cache fills, 64 writers stalled a whole socket and once reset the host;
    # 8 wrote faster (13 GB/s) without a stall.
    ap.add_argument("--load-threads", type=int, default=8)
    ap.add_argument("--seconds", type=int, default=60)
    ap.add_argument("--seeds", default="1310,1311")
    ap.add_argument(
        "--patterns",
        default="U128:65536,U512:262144,Z1024:0",
        help="tag:hot keys (0 = Zipfian)",
    )
    ap.add_argument(
        "--mark",
        required=True,
        help="command prefix for cellmark.py, run as '!<mark> pre|post ...'",
    )
    ap.add_argument("--skip-load", action="store_true")
    ap.add_argument(
        "--arms",
        default="S,S0",
        help="arms alternated per cell; one arm gives a single-arm session",
    )
    # S loads with IM on, so the data the device evicts while loading is parked rather than left mapped.
    ap.add_argument("--load-arm", default="S0")
    a = ap.parse_args()

    common = f"--region anon:{a.node} --dataset-gib {a.gib:g} --record {REC}"
    pats = [(t, int(h)) for t, h in (p.split(":") for p in a.patterns.split(","))]
    grid = [(p, int(n)) for p in pats for n in a.threads.split(",")]
    arms = tuple(a.arms.split(","))
    order = [
        (p, n, arm)
        for i, (p, n) in enumerate(grid)
        for arm in (arms if i % 2 == 0 else arms[::-1])
    ]

    print("# generated by nm_session.py")
    if not a.skip_load:
        print(f"!{a.mark} pre load {a.load_arm}")
        print(f"kv-load {common} --threads {a.load_threads}")
        print(f"!{a.mark} post load")
    for b, seed in enumerate(int(s) for s in a.seeds.split(",")):
        for (tag, hot), n, arm in order if b == 0 else order[::-1]:
            label = f"{arm.lower()}{tag.lower()}t{n}b{b}"
            if hot:
                dist = f"--dist uniform --hot-keys {hot} --hot-frac 1.0 --long-us 1000"
            else:
                dist = "--dist zipfian"
            print(f"!{a.mark} pre {label} {arm}")
            print(
                f"kv-run {common} --threads {n} --workload C {dist} --seconds {a.seconds} --seed {seed}"
            )
            print(f"!{a.mark} post {label}")


if __name__ == "__main__":
    main()
